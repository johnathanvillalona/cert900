import { test, expect, type Page } from '@playwright/test'
const snapshot = async (page:Page) => JSON.parse((await page.getByTestId('snapshot').textContent())!)
test.beforeEach(async ({page})=>{
  await page.route('**/*',r=>new URL(r.request().url()).origin==='http://127.0.0.1:4175'?r.continue():r.abort())
})
test('real hook: batched action then grading, exactly-once notification and locked state',async({page})=>{
  await page.goto('/tests/simulations/harness.html')
  await expect.poll(async()=> (await snapshot(page)).answer?.state?.adapter?.lease).toBe('apipa')
  await page.getByRole('button',{name:'Release and grade in one event',exact:true}).click()
  await expect(page.getByTestId('events')).toHaveText('[0.3333333333333333]')
  const before=await snapshot(page)
  expect(before.graded).toBe(1/3)
  for(const name of ['Grade twice','Renew','Reset simulation','Legacy terminal setter']) await page.getByRole('button',{name,exact:true}).click()
  expect((await snapshot(page)).answer).toEqual(before.answer)
  await expect(page.getByTestId('events')).toHaveText('[0.3333333333333333]')
  await page.getByRole('button',{name:'Retry fresh attempt'}).click()
  await expect.poll(async()=> (await snapshot(page)).answer?.state?.adapter?.lease).toBe('apipa')
  await page.getByRole('button',{name:'Release and grade in one event'}).click()
  await expect(page.getByTestId('events')).toHaveText('[0.3333333333333333,0.3333333333333333]')
})
test('real hook: model survives navigation, authoritative reset is isolated and version is frozen',async({page})=>{
  await page.goto('/tests/simulations/harness.html')
  await expect.poll(async()=> (await snapshot(page)).answer?.state?.adapter?.lease).toBe('apipa')
  await page.getByRole('button',{name:'Release',exact:true}).click()
  await page.getByRole('button',{name:'Other question'}).click()
  await page.getByRole('button',{name:'Set legacy match'}).click()
  const other=await snapshot(page)
  await page.getByRole('button',{name:'Return to DHCP'}).click()
  expect((await snapshot(page)).answer.state.adapter.lease).toBe('released')
  await page.getByRole('button',{name:'Replace binding prop'}).click()
  expect((await snapshot(page)).version).toBe(1)
  await page.getByRole('button',{name:'Reset simulation'}).click()
  expect((await snapshot(page)).answer.state.adapter.lease).toBe('apipa')
  await page.getByRole('button',{name:'Other question'}).click()
  expect((await snapshot(page)).answer).toEqual(other.answer)
})
test('exam: same scoring entry, vendor weight/scaling, one progress fold and post-finish lock',async({page})=>{
  await page.goto('/tests/simulations/harness.html?mode=exam')
  await expect.poll(async()=> (await snapshot(page)).answer?.state?.adapter?.lease).toBe('apipa')
  for(const name of ['Release','Renew','Flush DNS','Grade twice']) await page.getByRole('button',{name,exact:true}).click()
  await expect(page.getByTestId('events')).toHaveText('[]')
  const completed=await snapshot(page)
  expect(completed.graded).toBeUndefined()
  expect(completed.review.find((r:{title:string})=>r.title==='Fix a Stale DHCP Lease').frac).toBe(1)
  // Two CompTIA PBQs at weight 2 and one unanswered MC at weight 1.
  expect(completed.pct).toBe(2/5)
  expect(completed.scaled).toBe(420)
  await page.getByRole('button',{name:'Finish twice'}).click()
  await expect.poll(async()=> (await snapshot(page)).commits).toBe(1)
  expect((await snapshot(page)).progress.topics['troubleshooting-networks']).toEqual({c:1,t:1})
  await page.getByRole('button',{name:'Reset simulation'}).click()
  expect((await snapshot(page)).answer).toEqual(completed.answer)
  await page.getByRole('button',{name:'Finish twice'}).click()
  expect((await snapshot(page)).commits).toBe(1)
})
