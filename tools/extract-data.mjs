// Extracts the exam banks from the legacy single-file app (legacy/index.html)
// and emits typed data modules under src/data/. Run: npm run extract-data
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const html = fs.readFileSync(path.join(root, "legacy", "index.html"), "utf8")
const m = html.match(/<script>([\s\S]*)<\/script>/)
if (!m) { console.error("no <script> block found in legacy/index.html"); process.exit(1) }

// browser-global stubs (same approach as tools/linkcheck.js)
const fakeEl = new Proxy({}, {
  get(t, p) {
    if (p === "classList") return { add() {}, remove() {}, toggle() {} }
    if (p === "style") return {}
    if (p === "dataset") return { v: "0" }
    if (p === "querySelectorAll") return () => []
    if (p === "querySelector") return () => fakeEl
    if (typeof p === "string") return typeof t[p] === "function" ? t[p] : (t[p] ?? function () {})
    return undefined
  },
  set(t, p, v) { t[p] = v; return true },
})
global.document = { getElementById: () => fakeEl, querySelectorAll: () => [], querySelector: () => fakeEl, documentElement: fakeEl }
global.window = { scrollTo() {}, matchMedia: () => ({ matches: false }) }
global.matchMedia = () => ({ matches: false })
global.localStorage = { getItem: () => null, setItem() {}, removeItem() {} }
global.setInterval = () => 0
global.clearInterval = () => {}
global.confirm = () => true
global.alert = () => {}

;(0, eval)(m[1] + "\n;globalThis.__EXAMS = EXAMS; globalThis.__ORDER = EXAM_ORDER;")
const EXAMS = globalThis.__EXAMS
const ORDER = globalThis.__ORDER

const outDir = path.join(root, "src", "data")
fs.mkdirSync(outDir, { recursive: true })

const HEADER = "// GENERATED by tools/extract-data.mjs from legacy/index.html — do not edit by hand.\n// Re-run: npm run extract-data\n"

for (const id of Object.keys(EXAMS)) {
  const ex = EXAMS[id]
  const def = {
    id: ex.id, cert: ex.cert, name: ex.name, code: ex.code, blurb: ex.blurb,
    domains: ex.domains, examSplit: ex.examSplit,
    examMC: ex.examMC, examPBQ: ex.examPBQ, examMinutes: ex.examMinutes,
    videos: ex.videos, questions: ex.questions, pbqs: ex.pbqs,
  }
  const ts = HEADER +
    'import type { ExamDef } from "./types"\n\n' +
    "export const exam: ExamDef = " + JSON.stringify(def, null, 1) + "\n"
  fs.writeFileSync(path.join(outDir, `${id}.ts`), ts)
  console.log(`${id}: ${ex.questions.length} questions, ${ex.pbqs.length} pbqs, ${Object.keys(ex.videos).length} videos`)
}

const index = HEADER + `import type { ExamDef } from "./types"
${Object.keys(EXAMS).map((id, i) => `import { exam as e${i} } from "./${id}"`).join("\n")}

export const EXAMS: Record<string, ExamDef> = {
${Object.keys(EXAMS).map((id, i) => ` "${id}": e${i},`).join("\n")}
}

export const EXAM_ORDER: string[] = ${JSON.stringify(ORDER)}
`
fs.writeFileSync(path.join(outDir, "index.ts"), index)
console.log("wrote src/data/index.ts")
