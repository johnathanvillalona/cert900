/**
 * SEO guide pages. These components are prerendered to static HTML at build
 * time (tools/prerender.tsx), so they must stay hook-free and context-free:
 * plain props, static EXAMS data, native <details> for interactivity.
 * FAQ content is exported so the prerenderer can emit matching JSON-LD.
 */

/**
 * Real bank questions for this exam, generated by tools/gen-meta.mjs and spread
 * across its domains.
 *
 * Replaces three hand-copied examples per page. The answer sits inside a native
 * <details>, so it is present in the prerendered HTML and fully crawlable while
 * still hidden until a reader asks for it.
 */
function Samples({ examIds, limit = 8 }: { examIds: string[]; limit?: number }) {
  // Interleave when a page covers more than one exam (the A+ hub covers both
  // cores), so the set is not all Core 1 followed by all Core 2.
  const lanes = examIds.map((id) => (GUIDE_SAMPLES[id] ?? []).map((q) => ({ q, code: EXAM_META[id].code })))
  const merged: { q: GuideSample; code: string }[] = []
  for (let i = 0; merged.length < limit; i++) {
    let added = false
    for (const lane of lanes) {
      if (merged.length >= limit) break
      if (i < lane.length) {
        merged.push(lane[i])
        added = true
      }
    }
    if (!added) break
  }

  return (
    <div className="flex flex-col gap-4">
      {merged.map(({ q, code }, n) => (
        <div key={`${code}-${q.id}`} className="rounded-lg border bg-card p-5">
          <p className="font-mono text-[11px] uppercase tracking-wider text-muted-foreground">
            Sample question {n + 1} · {code} · {q.domain}
          </p>
          <p className="mt-2 font-medium leading-snug">{q.x}</p>
          <ol className="mt-3 flex flex-col gap-1.5 text-sm">
            {q.o.map((o, i) => (
              <li key={i} className="flex items-start gap-2.5 rounded-md border px-3 py-2">
                <span className="flex size-5 shrink-0 items-center justify-center rounded-sm border font-mono text-[11px] font-semibold">
                  {"ABCD"[i]}
                </span>
                {o}
              </li>
            ))}
          </ol>
          <details className="group mt-3">
            <summary className="cursor-pointer list-none font-medium text-brand underline-offset-4 hover:underline [&::-webkit-details-marker]:hidden">
              Show answer and explanation
            </summary>
            <div className="mt-2 rounded-md border border-success/50 bg-success/10 p-3 text-sm">
              <p className="flex items-center gap-1.5 font-semibold text-success">
                <Check className="size-4" strokeWidth={2.5} /> {"ABCD"[q.a]}. {q.o[q.a]}
              </p>
              <p className="text-muted-foreground mt-1">{q.e}</p>
              <p className="text-muted-foreground mt-2 font-mono text-xs">Topic: {q.topic}</p>
            </div>
          </details>
        </div>
      ))}
    </div>
  )
}

function DomainTable({ examId }: { examId: string }) {
  const exam = EXAM_META[examId]
  const keys = Object.keys(exam.domains).map(Number)
  // The number of questions we hold per domain, so the table says what this
  // site actually offers rather than only restating the published blueprint.
  const perDomain = (d: number) => Math.round((exam.examSplit[d] ?? 0) * exam.questionCount)
  return (
    <div className="overflow-x-auto">
      <table className="mt-3 w-full min-w-105 border-collapse text-sm">
        <thead>
          <tr className="border-b text-left">
            <th className="py-2 pr-4 font-semibold">{exam.code} domain</th>
            <th className="py-2 pr-4 font-mono font-semibold">Exam weight</th>
            <th className="py-2 font-mono font-semibold">Questions here</th>
          </tr>
        </thead>
        <tbody>
          {keys.map((dk) => (
            <tr key={dk} className="border-b">
              <td className="py-2 pr-4">{exam.domains[dk]}</td>
              <td className="py-2 pr-4 font-mono tabular-nums">{Math.round((exam.examSplit[dk] ?? 0) * 100)}%</td>
              <td className="py-2 font-mono tabular-nums">about {perDomain(dk)}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

